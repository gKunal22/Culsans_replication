#!/usr/bin/env python3
"""Generate simulator/synthesis file lists for the Culsans SoC.

Reads the output of `make -f scripts/flist.mk print` (the authors' own source
ordering) and writes, with paths relative to the repository root:

  build/filelists/culsans_rtl.f     plain list (+incdir+, +define+) for Verilator
  build/filelists/culsans_rtl.prj   Vivado xvlog/xvhdl project file (XSim)
  build/filelists/culsans_rtl.tcl   Tcl lists (culsans_sv, culsans_vhdl, culsans_incdirs) for Vivado

Usage: python3 scripts/gen_filelists.py <flist.txt> [--exclude PATTERN ...] [--extra FILE ...]
"""
import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def rel(p):
    p = os.path.normpath(os.path.realpath(p) if os.path.islink(p) else os.path.abspath(p))
    r = os.path.relpath(p, ROOT)
    return r.replace(os.sep, "/")


def expand_flist(path, env, files, incdirs):
    with open(path) as fh:
        for line in fh:
            line = line.split("//")[0].strip()
            if not line:
                continue
            line = re.sub(r"\$\{(\w+)\}", lambda m: env[m.group(1)], line)
            if line.startswith("+incdir+"):
                incdirs.append(line[len("+incdir+"):])
            elif line.startswith("-F") or line.startswith("-f"):
                expand_flist(line[2:].strip(), env, files, incdirs)
            else:
                files.append(line)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("flist")
    ap.add_argument("--exclude", action="append", default=[],
                    help="substring; matching source files are dropped")
    ap.add_argument("--extra", action="append", default=[],
                    help="extra SystemVerilog file appended at the end")
    ap.add_argument("--define", action="append", default=[])
    ap.add_argument("--replace", action="append", default=[],
                    help="BASENAME=PATH: use PATH instead of the source file named BASENAME")
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "filelists"))
    ap.add_argument("--name", default="culsans_rtl")
    a = ap.parse_args()

    env = {}
    files, incdirs, vhdl = [], [], []
    flists = []
    with open(a.flist) as fh:
        lines = [l.rstrip("\n") for l in fh]
    for l in lines:
        if l.startswith("#TARGET "):
            env["TARGET_CFG"] = l.split()[1]
        elif l.startswith("#CVA6_REPO_DIR "):
            env["CVA6_REPO_DIR"] = l.split()[1]
        elif l.startswith("#INCDIR "):
            incdirs += l.split()[1:]
        elif l.startswith("#FLIST "):
            flists.append(l.split()[1])
    for f in flists:
        expand_flist(f, env, files, incdirs)
    # order used by the authors: flists, packages, src, LLC, culsans
    for kind in ("PKG", "SRC", "LLC", "CUL"):
        for l in lines:
            if l.startswith(kind + " "):
                files.append(l.split(None, 1)[1])
    for l in lines:
        if l.startswith("VHD "):
            vhdl.append(l.split(None, 1)[1])
    files += a.extra

    repl = dict(r.split("=", 1) for r in a.replace)
    files = [repl.get(os.path.basename(f), f) for f in files]
    seen, sv = set(), []
    for f in files:
        k = os.path.abspath(f)
        if k in seen or any(x in f for x in a.exclude):
            continue
        seen.add(k)
        sv.append(rel(f))
    inc = []
    for d in incdirs:
        r = rel(d)
        if r not in inc:
            inc.append(r)
    vhdl = [rel(v) for v in vhdl if not any(x in v for x in a.exclude)]

    os.makedirs(a.out, exist_ok=True)
    base = os.path.join(a.out, a.name)
    with open(base + ".f", "w") as fh:
        for d in inc:
            fh.write(f"+incdir+{d}\n")
        for d in a.define:
            fh.write(f"+define+{d}\n")
        fh.write("\n".join(sv) + "\n")
    with open(base + ".prj", "w") as fh:
        incs = " ".join(f'-i "{d}"' for d in inc)
        defs = " ".join(f"-d {d}" for d in a.define)
        for f in sv:
            fh.write(f'sv work "{f}" {incs} {defs}\n'.replace("  ", " "))
        for f in vhdl:
            fh.write(f'vhdl work "{f}"\n')
    with open(base + ".tcl", "w") as fh:
        fh.write("# generated by scripts/gen_filelists.py; paths relative to the repository root\n")
        fh.write("set culsans_incdirs [list " + " ".join(inc) + "]\n")
        fh.write("set culsans_defines [list " + " ".join(a.define) + "]\n")
        fh.write("set culsans_sv [list \\\n" + "".join(f"  {f} \\\n" for f in sv) + "]\n")
        fh.write("set culsans_vhdl [list " + " ".join(vhdl) + "]\n")
    print(f"{len(sv)} SV files, {len(vhdl)} VHDL files, {len(inc)} include dirs -> {base}.{{f,prj,tcl}}")


if __name__ == "__main__":
    sys.exit(main())
